"""Live numbers for presentation/slides.html (`make slides`).

Queries Trino through the running stack and writes presentation/slides-data.js
(`window.SLIDES_DATA = {...}`), which the slides load with a <script> tag (works from file://).
If the stack is down it only warns: the slides fall back to the snapshot embedded in the HTML.
Standard library only; runs on the host.
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "presentation" / "slides-data.js"

COUNTED_TABLES = [
    "bronze.logs_index_raw", "bronze.telemetry_raw", "bronze.log_messages_raw", "bronze.rejected_records",
    "silver.stg_logs", "silver.fct_flight", "silver.fct_mode_segment", "silver.fct_telemetry_1min",
    "silver.dim_vehicle", "silver.dim_flight_mode", "silver.dim_date", "silver.snap_vehicles",
    "gold.mart_flights_by_class_month", "gold.mart_flight_mode_usage", "gold.mart_reliability_daily",
    "gold.mart_firmware_adoption", "gold.mart_flight_envelope", "gold.mart_battery_efficiency",
    "gold.mart_vehicle_utilization", "gold.mart_top_log_messages", "gold.mart_pipeline_runs",
]

KPIS = """
SELECT
  (SELECT count(*) FROM bronze.logs_index_raw) AS index_logs,
  (SELECT min(log_date) FROM bronze.logs_index_raw) AS first_upload,
  (SELECT max(log_date) FROM bronze.logs_index_raw) AS last_upload,
  (SELECT round(count(*) / 90e0) FROM bronze.logs_index_raw
     WHERE log_date >= current_date - INTERVAL '91' DAY AND log_date < current_date - INTERVAL '1' DAY) AS logs_per_day,
  (SELECT round(100e0 * count_if(json_extract_scalar(payload, '$.wind_speed') = '-1') / count(*), 1)
     FROM bronze.logs_index_raw) AS wind_unknown_pct,
  (SELECT count_if(not is_simulation) FROM silver.fct_flight) AS real_logs,
  (SELECT round(100e0 * count_if(is_simulation) / count(*), 1) FROM silver.fct_flight) AS sim_pct,
  (SELECT round(sum(duration_s) / 3600e0) FROM silver.fct_flight WHERE not is_simulation) AS flight_hours,
  (SELECT count(DISTINCT vehicle_uuid) FROM silver.fct_flight WHERE not is_simulation) AS vehicles,
  (SELECT count(DISTINCT log_id) FROM audit.ulog_downloads WHERE status = 'parsed') AS ulogs_parsed,
  (SELECT round(sum(bytes) / 1e6) FROM audit.ulog_downloads WHERE status = 'downloaded' AND reason IS NULL) AS ulog_mb,
  (SELECT count(*) FROM audit.ingestion_runs) AS pipeline_runs
"""

SAMPLE = """
SELECT payload FROM bronze.logs_index_raw
WHERE log_date = (SELECT max(log_date) FROM bronze.logs_index_raw)
  AND json_extract_scalar(payload, '$.airframe_name') <> ''
  AND json_extract_scalar(payload, '$.sys_hw') NOT LIKE '%SITL%'
ORDER BY log_id LIMIT 1
"""


def trino(sql: str) -> list[dict]:
    """Run one statement in the trino container; JSON output = one object per line."""
    out = subprocess.run(
        ["docker", "compose", "exec", "-T", "trino", "trino", "--catalog", "iceberg", "--output-format", "JSON",
         "--execute", sql],
        capture_output=True, text=True, timeout=120)
    if out.returncode != 0:
        raise RuntimeError(out.stderr.strip().splitlines()[-1] if out.stderr.strip() else "trino failed")
    return [json.loads(line) for line in out.stdout.splitlines() if line.startswith("{")]


def main() -> int:
    try:
        kpis = trino(KPIS)[0]
        counts_sql = " UNION ALL ".join(f"SELECT '{t}' AS t, count(*) AS n FROM {t}" for t in COUNTED_TABLES)
        counts = {r["t"]: r["n"] for r in trino(counts_sql)}
        sample = json.loads(trino(SAMPLE)[0]["payload"])
    except Exception as e:  # stack down, Trino starting, ...: keep the slides usable
        print(f"slides: live numbers unavailable ({e}); the slides show their embedded snapshot", file=sys.stderr)
        return 0
    data = {"generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "kpis": kpis,
            "counts": counts, "sample_record": sample}
    OUT.write_text("// Generated by infrastructure/scripts/slides_data.py (make slides). Do not edit.\n"
                   f"window.SLIDES_DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n")
    print(f"slides: live numbers written to {OUT.relative_to(OUT.parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
